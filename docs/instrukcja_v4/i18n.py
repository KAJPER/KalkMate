def _names(d):
    strip = lambda s: re.sub(r"^\s*(\d+\.|\[\d\])\s*", "", s).strip()  # noqa: E731
    n = {"LANGS": LANG_LIST}
    get = d.get
    if get("m1"):
        n["M1"], n["SOLVE"] = d["m1"], strip(d["m1"])
    if get("m5"):
        n["M5"], n["SET"] = d["m5"], strip(d["m5"])
    if get("set_wifi"):
        n["WIFI"] = d["set_wifi"].split(" (")[0]
    for k, key in (("PHOTO", "sol_m1"), ("TEXT", "sol_m2"), ("HIST", "sol_hist")):
        if get(key):
            n[k] = strip(d[key])
    for k, key in (("CODE", "code_lbl"), ("DEVID", "set_dev"), ("PANIC", "panic_lbl"), ("UPD", "upd_lbl"),
                   ("BAT", "bat_lbl"), ("LANG", "lang_lbl"), ("LOWBAT", "low_bat")):
        if get(key):
            n[k] = d[key]
    return n


def _fill(v, names, lang):
    if isinstance(v, list):
        return [_fill(x, names, lang) for x in v]
    if not isinstance(v, str):
        return v

    def rep(m):
        if m.group(1) not in names:
            raise KeyError(f"[{lang}] brak napisu dla {{{m.group(1)}}}")
        return names[m.group(1)]
    v = re.sub(r"\{([A-Z0-9]+)\}", rep, v)
    v = re.sub(r"(?<!\.)\.\.(?!\.)", ".", v)  # napis z ekranu konczy sie kropka ("Histor.") + kropka zdania
    # twarde spacje: "200 000", "2 h", "5 V", "+2 mln" — bez lamania wiersza w srodku
    v = re.sub(r"(?<=\d) (?=\d{3}\b)", "\u00a0", v)
    v = v.replace(" + QR", "\u00a0+\u00a0QR")
    v = re.sub(r"(?<=\d) (?=(?:h|V|s|с|min|хв|GHz|ГГц|mAh|гадз|mln|mil|млн|tis|tūkst|Mio|millions|milhões|millones|milioni)\b)",
               "\u00a0", v)
    return v


