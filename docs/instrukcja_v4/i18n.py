def _lbl(s):
    """'AI code:  ' / 'Battery...' / '=== Updates ===' -> 'AI code' / 'Battery' / 'Updates'."""
    return s.strip().strip("=").strip().rstrip(".").rstrip(":").strip()


def _item(s, prefix):
    """Pozycja menu z prefiksem ('1. ' / '[1] ') — bez kursora '> ' i wciecia."""
    s = re.sub(r"^\s*>?\s*", "", s).rstrip()
    return s if s.startswith(prefix) else prefix + s


def _load_fw(lang, d):
    src = {k: "own" for k in d}
    path = os.path.join(FW_DIR, f"fw_{lang}.json")
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            fw = json.load(f)
        for key, cands in _FW_KEYS.items():
            for c in cands:
                v = fw.get(c)
                if isinstance(v, dict):
                    v = v.get(lang)
                if isinstance(v, str) and v.strip():
                    if key == "qr":
                        a, _, b = v.partition("->")
                        d["qr_hint1"], d["qr_hint2"] = a.strip() + " ->", b.strip()
                        src["qr_hint1"] = src["qr_hint2"] = "fw"
                    else:
                        if key.endswith("_lbl"):
                            v = _lbl(v)
                        elif key in ("m1", "m2", "m5"):
                            v = _item(v, key[1] + ". ")
                        elif key.startswith("sol_"):
                            v = _item(v, {"sol_m1": "[1] ", "sol_m2": "[2] ", "sol_hist": "[3] "}[key])
                        d[key] = v.strip() if not key == "res_foot" else v
                        src[key] = "fw"
                    break
    DEV_SRC[lang] = src


